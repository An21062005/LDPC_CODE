"""Mapper / scheduler for the adaptive QC decoder (code/rtl/adaptive).

  python script/mapper.py hw                           # write adaptive_hw_pkg.sv
  python script/mapper.py hw --check                   # verify it is up to date
  python script/mapper.py map --code wifi_648_r12 --p 6 --c 3
  python script/mapper.py sweep                        # every code x allowed P x C
  python script/mapper.py select --code wifi_1296_r12 --max-latency-us 200

Hardware (code/configs/hw_limits.yaml): one message bank per block position in
the union of the hardware codes, VN unit p may serve the columns in its
candidate set, CN unit q the rows in its candidate set. Candidate sets follow
from the round-robin policy (column c -> unit c mod P, step c div P) for every
allowed P (and rows likewise for C), so routing is fixed at synthesis.

A map is checked by replaying the schedule cycle by cycle with the RTL pipeline
latencies (VN write = read + 3 clocks, CN write = read + 2):
  * every edge of H is read and written exactly once per phase, at the bank
    and address that hold it, and the VN and CN views agree;
  * per bank and clock at most one read and one write;
  * no address is written before it is read in the same phase;
  * every (unit, column/row) assignment is inside the unit's routing set.
The cycle estimate comes from that replay (per iteration: VN issue + 3, CN
issue + 2, 1 evaluation clock; 18 iterations), not from the code degrees.
"""
import argparse
from collections import defaultdict
import json
from pathlib import Path
import sys

import numpy as np
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from adaptive_lib import ITERATIONS, ROOT, base_matrix, build_h, load_code  # noqa: E402

PKG = ROOT / "code/rtl/generated/adaptive_hw_pkg.sv"
VN_LAT, CN_LAT = 3, 2
NONE = 255


def load_hw():
    return yaml.safe_load((ROOT / "code/configs/hw_limits.yaml").read_text(encoding="utf-8"))


def hardware(hw):
    g = hw["qc_grid"]
    mb, nb = g["block_rows"], g["block_cols"]
    union = np.zeros((mb, nb), dtype=bool)
    for name in hw["codes_in_hardware"]:
        b = base_matrix(load_code(name))
        if b is None or b.shape != (mb, nb):
            raise ValueError(f"{name}: not a {mb}x{nb} QC code")
        union |= b >= 0
    pos = [(r, c) for r in range(mb) for c in range(nb) if union[r, c]]       # row-major
    pos_at = np.full((mb, nb), NONE, dtype=int)
    for i, (r, c) in enumerate(pos):
        pos_at[r, c] = i
    row_slot = [[i for i, (rr, _) in enumerate(pos) if rr == r] for r in range(mb)]
    pe = hw["pe_cluster"]
    vcand = [sorted({c for c in range(nb) for p_act in pe["allowed_p_act"] if p < p_act and c % p_act == p})
             for p in range(pe["vn_units"])]
    ccand = [sorted({r for r in range(mb) for c_act in pe["allowed_c_act"] if q < c_act and r % c_act == q})
             for q in range(pe["cn_units"])]
    return dict(mb=mb, nb=nb, zmax=g["z_max"], zset=g["z_supported"], pos=pos, pos_at=pos_at,
                row_slot=row_slot, dcs=max(len(s) for s in row_slot), dvs=pe["vn_unit_slots"],
                pv=pe["vn_units"], pc=pe["cn_units"], kv=nb, kc=mb, vcand=vcand, ccand=ccand,
                allowed_p=pe["allowed_p_act"], allowed_c=pe["allowed_c_act"],
                cn_deg_max=pe["cn_active_degree_max"], clock_mhz=hw["target"]["decoder_clock_mhz"])


def render_pkg(t):
    def p8(name, vals):
        return f"  localparam [{len(vals)}*8-1:0] {name} = {{" + ", ".join(f"8'd{v}" for v in reversed(vals)) + "};\n"
    vcmax, ccmax = max(map(len, t["vcand"])), max(map(len, t["ccand"]))
    pad = lambda lists, w: [x for l in lists for x in (l + [NONE] * (w - len(l)))]
    s = "// GENERATED by script/mapper.py hw from code/configs/hw_limits.yaml - do not edit.\n"
    s += "package adaptive_hw_pkg;\n"
    for k, v in (("MB", t["mb"]), ("NB", t["nb"]), ("ZMAX", t["zmax"]), ("NPOS", len(t["pos"])),
                 ("PV", t["pv"]), ("PC", t["pc"]), ("KV", t["kv"]), ("KC", t["kc"]),
                 ("DVS", t["dvs"]), ("DCS", t["dcs"]), ("VCMAX", vcmax), ("CCMAX", ccmax)):
        s += f"  localparam integer {k} = {v};\n"
    s += p8("POS_ROW", [r for r, _ in t["pos"]]) + p8("POS_COL", [c for _, c in t["pos"]])
    s += p8("POS_AT", [int(v) for v in t["pos_at"].flatten()])                 # [r*NB + c]
    s += p8("ROW_SLOT_POS", pad(t["row_slot"], t["dcs"]))                       # [r*DCS + slot]
    s += p8("VCAND_N", [len(l) for l in t["vcand"]]) + p8("VCAND", pad(t["vcand"], vcmax))
    s += p8("CCAND_N", [len(l) for l in t["ccand"]]) + p8("CCAND", pad(t["ccand"], ccmax))
    return s + "endpackage\n"


def qc_analysis(h):
    """For every block size Z dividing both H dimensions, count Z x Z blocks
    that are zero, a cyclic shift of the identity, or neither. A code runs on
    the shared banks only if some Z gives 'neither' = 0 on the hardware grid."""
    m, n = h.shape
    res = []
    for z in range(2, min(m, n) + 1):
        if m % z or n % z:
            continue
        zero = circ = other = 0
        for r in range(m // z):
            for c in range(n // z):
                blk = h[r * z:(r + 1) * z, c * z:(c + 1) * z]
                if not blk.any():
                    zero += 1
                elif blk.sum() == z and all(blk[i, (i + int(np.argmax(blk[0]))) % z] for i in range(z)):
                    circ += 1
                else:
                    other += 1
        res.append(dict(z=z, grid=[m // z, n // z], zero=zero, circulant=circ, other=other))
    return res


def make_map(t, code, p_act, c_act, vsched=None, csched=None):
    """Tables + cycle-level verification for (code, P_act, C_act)."""
    cfg = load_code(code)
    issues = []
    b = base_matrix(cfg)
    if b is None:
        qa = [r for r in qc_analysis(build_h(cfg)) if r["z"] in (16, 24, 32, 48)]
        return dict(code=code, p_act=p_act, c_act=c_act, ok=False, qc_analysis=qa,
                    issues=["not a QC code: the shared banks hold Z x Z circulant blocks only; "
                            + "; ".join(f"Z={r['z']} grid {r['grid']}: {r['other']} non-circulant blocks" for r in qa)])
    z = int(cfg["structure"]["z"])
    if b.shape != (t["mb"], t["nb"]):
        issues.append(f"base matrix {b.shape} != hardware grid {(t['mb'], t['nb'])}")
    if z not in t["zset"]:
        issues.append(f"Z={z} not in supported {t['zset']}")
    if p_act not in t["allowed_p"]:
        issues.append(f"P_act={p_act} not in {t['allowed_p']}")
    if c_act not in t["allowed_c"]:
        issues.append(f"C_act={c_act} not in {t['allowed_c']}")
    if issues:
        return dict(code=code, p_act=p_act, c_act=c_act, ok=False, issues=issues)
    mb, nb = b.shape
    nz = b >= 0
    for r, c in zip(*np.nonzero(nz)):
        if t["pos_at"][r, c] == NONE:
            issues.append(f"block ({r},{c}) has no bank in this hardware")
    if (nz.sum(1) > t["cn_deg_max"]).any():
        issues.append(f"row degree > {t['cn_deg_max']} (7-bit CN sum)")
    if (nz.sum(0) > t["dvs"]).any():
        issues.append("column degree > VN unit slots")
    # Round-robin assignment (the policy the routing was built for).
    if vsched is None:                                 # (unit, step) -> block column
        vsched = {(c % p_act, c // p_act): c for c in range(nb)}
    if csched is None:                                 # (unit, step) -> block row
        csched = {(r % c_act, r // c_act): r for r in range(mb)}
    # The RTL issues steps 0 .. steps-1 only, so the step registers written to
    # the core come from the schedule itself (= ceil(24/P), ceil(12/C) for
    # round-robin), and every (unit, step) must exist in the hardware tables.
    vsteps = max(k for _, k in vsched) + 1
    csteps = max(k for _, k in csched) + 1
    for (p, k), c in vsched.items():
        if not (0 <= p < t["pv"] and 0 <= k < t["kv"]):
            issues.append(f"VN (unit {p}, step {k}) outside the {t['pv']}x{t['kv']} schedule table")
        elif c not in t["vcand"][p]:
            issues.append(f"VN unit {p} cannot reach column {c}")
    for (q, k), r in csched.items():
        if not (0 <= q < t["pc"] and 0 <= k < t["kc"]):
            issues.append(f"CN (unit {q}, step {k}) outside the {t['pc']}x{t['kc']} schedule table")
        elif r not in t["ccand"][q]:
            issues.append(f"CN unit {q} cannot reach row {r}")
    if issues:
        return dict(code=code, p_act=p_act, c_act=c_act, ok=False, issues=issues)
    # Cycle replay.
    h = build_h(cfg)
    edges = {(int(m_), int(n_)) for m_, n_ in zip(*np.nonzero(h))}
    stats = {}
    for phase, sched, steps, lat in (("VN", vsched, vsteps, VN_LAT), ("CN", csched, csteps, CN_LAT)):
        reads, writes = defaultdict(int), defaultdict(int)          # (bank, clock) -> count
        first_read, write_at = {}, {}                              # (bank, addr) -> clock
        seen = set()
        for (unit, k), idx in sched.items():
            for i in range(z):
                clk = k * z + i
                if phase == "VN":
                    c = idx
                    banks = [(int(t["pos_at"][r, c]), r, c, i) for r in range(mb) if nz[r, c]]
                else:
                    r = idx
                    banks = [(int(t["pos_at"][r, c]), r, c, (i + int(b[r, c])) % z) for c in range(nb) if nz[r, c]]
                for bank, r, c, addr in banks:
                    edge = (r * z + (addr - int(b[r, c])) % z, c * z + addr)
                    if edge not in edges:
                        issues.append(f"{phase}: bank {bank} addr {addr} is not an edge of H")
                    if edge in seen:
                        issues.append(f"{phase}: edge {edge} processed twice")
                    seen.add(edge)
                    reads[(bank, clk)] += 1
                    writes[(bank, clk + lat)] += 1
                    key = (bank, addr)
                    if key in first_read:
                        issues.append(f"{phase}: bank {bank} addr {addr} read twice")
                    first_read[key] = clk
                    write_at[key] = clk + lat
        if seen != edges:
            issues.append(f"{phase}: {len(edges - seen)} edges never processed")
        if any(v > 1 for v in reads.values()) or any(v > 1 for v in writes.values()):
            issues.append(f"{phase}: bank port conflict")
        for key, wclk in write_at.items():                          # write after every read of that word
            if wclk <= first_read[key]:
                issues.append(f"{phase}: bank {key[0]} addr {key[1]} written before read")
        # A write must not hit a word another unit still has to read later in the phase.
        last_clock = max(first_read.values())
        stats[phase] = dict(steps=steps, issue_clocks=steps * z, last_write_clock=max(write_at.values()) + 1,
                            max_bank_reads_per_clock=max(reads.values()), max_bank_writes_per_clock=max(writes.values()),
                            last_read_clock=last_clock + 1)
    per_iter = stats["VN"]["last_write_clock"] + stats["CN"]["last_write_clock"] + 1
    cycles = ITERATIONS * per_iter
    cfgimg = [] if issues else [(0x000, z), (0x001, vsteps), (0x002, csteps)]
    for i, (r, c) in enumerate(t["pos"] if not issues else []):
        cfgimg.append((0x100 + i, (1 << 6 | int(b[r, c])) if nz[r, c] else 0))
    for p in range(t["pv"] if not issues else 0):
        for k in range(t["kv"]):
            c = vsched.get((p, k))
            cfgimg.append((0x400 + p * t["kv"] + k, (0x80 | t["vcand"][p].index(c)) if c is not None else 0))
    for q in range(t["pc"] if not issues else 0):
        for k in range(t["kc"]):
            r = csched.get((q, k))
            cfgimg.append((0x800 + q * t["kc"] + k, (0x80 | t["ccand"][q].index(r)) if r is not None else 0))
    n, k_info = h.shape[1], h.shape[1] - h.shape[0]
    us = cycles / t["clock_mhz"]
    return dict(code=code, n=n, k=k_info, z=z, p_act=p_act, c_act=c_act, ok=not issues, issues=sorted(set(issues))[:20],
                vn_steps=vsteps, cn_steps=csteps, phases=stats, cycles_per_iteration=per_iter,
                decode_cycles_estimate=cycles, latency_us=round(us, 2),
                core_throughput_mbps=round(n / us, 3), info_throughput_mbps=round(k_info / us, 3),
                vn_schedule={f"{p},{k}": c for (p, k), c in sorted(vsched.items())},
                cn_schedule={f"{q},{k}": r for (q, k), r in sorted(csched.items())}, config=cfgimg)


def write_map(m, out):
    out.mkdir(parents=True, exist_ok=True)
    if "config" in m:                              # rejected maps have no image
        (out / "config.txt").write_text("".join(f"{a:03x} {d:04x}\n" for a, d in m["config"]), encoding="ascii")
    rep = {k: v for k, v in m.items() if k != "config"}
    (out / "report.json").write_text(json.dumps(rep, indent=2) + "\n", encoding="utf-8")


def select(t, code, max_latency_us=None, min_info_mbps=None, calibration=None):
    """Smallest active hardware (P_act + C_act) meeting the requirement.
    Uses the replayed cycle count; 'calibration' maps (P, C) -> measured RTL
    cycles and, when given, replaces the estimate."""
    cands = []
    for p in t["allowed_p"]:
        for c in t["allowed_c"]:
            m = make_map(t, code, p, c)
            if not m["ok"]:
                continue
            cyc = (calibration or {}).get((p, c), m["decode_cycles_estimate"])
            us = cyc / t["clock_mhz"]
            info = m["k"] / us
            if (max_latency_us is None or us <= max_latency_us) and (min_info_mbps is None or info >= min_info_mbps):
                cands.append((p + c, us, p, c, cyc, info))
    if not cands:
        return None
    _, us, p, c, cyc, info = min(cands)
    return dict(code=code, p_act=p, c_act=c, decode_cycles=cyc, latency_us=round(us, 2),
                info_throughput_mbps=round(info, 3), measured=(p, c) in (calibration or {}))


def selftest(t):
    """Corrupted schedules must be rejected (the checks are not vacuous)."""
    code, p, c = "wifi_648_r12", 6, 3
    good_v = {(col % p, col // p): col for col in range(24)}
    good_c = {(r % c, r // c): r for r in range(12)}
    cases = {
        "column dropped": (dict(list(good_v.items())[:-1]), good_c),
        "column twice": ({**good_v, (0, 3): 1}, good_c),
        "column outside routing": ({**{k: v for k, v in good_v.items() if v != 5}, (5, 3): 4,
                                     (4, 3): 5}, good_c),
        "two rows in one step": ({**good_v}, {**good_c, (0, 0): 0, (1, 0): 0}),
        "step beyond table": ({**{k: v for k, v in good_v.items() if v != 23}, (5, t["kv"]): 23}, good_c),
    }
    ok = make_map(t, code, p, c)["ok"]
    out = {"reference map accepted": ok}
    for name, (v, cc) in cases.items():
        m = make_map(t, code, p, c, v, cc)
        out[name + " rejected"] = not m["ok"]
        print(f"{name:24} ok={m['ok']} first issue: {m['issues'][:1]}")
    print(json.dumps(out, indent=2))
    return 0 if all(out.values()) else 1


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("action", choices=("hw", "map", "sweep", "select", "selftest"))
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--code")
    ap.add_argument("--p", type=int)
    ap.add_argument("--c", type=int)
    ap.add_argument("--max-latency-us", type=float)
    ap.add_argument("--min-info-mbps", type=float)
    a = ap.parse_args(argv)
    t = hardware(load_hw())
    if a.action == "hw":
        text = render_pkg(t)
        if a.check:
            ok = PKG.is_file() and PKG.read_text(encoding="ascii") == text
            print("HW_PKG_" + ("UP_TO_DATE" if ok else "STALE"))
            return 0 if ok else 1
        PKG.parent.mkdir(parents=True, exist_ok=True)
        PKG.write_text(text, encoding="ascii", newline="\n")
        print(f"NPOS={len(t['pos'])} DCS={t['dcs']} VCAND={[len(v) for v in t['vcand']]} "
              f"CCAND={[len(v) for v in t['ccand']]} -> {PKG}")
        return 0
    if a.action == "selftest":
        return selftest(t)
    out = ROOT / "outfeed/maps"
    if a.action == "map":
        m = make_map(t, a.code, a.p, a.c)
        write_map(m, out / f"{a.code}_P{a.p}_C{a.c}")
        print(json.dumps({k: m[k] for k in m if k not in ("config", "vn_schedule", "cn_schedule")}, indent=2))
        return 0 if m["ok"] else 1
    if a.action == "sweep":
        rows = []
        for code in ["wifi_648_r12", "wifi_1296_r12", "da2_1152_r12"]:
            for p in t["allowed_p"]:
                for c in t["allowed_c"]:
                    m = make_map(t, code, p, c)
                    if m["ok"]:
                        write_map(m, out / f"{code}_P{p}_C{c}")
                    rows.append(dict(code=code, p_act=p, c_act=c, ok=m["ok"], issues=m["issues"][:2],
                                     cycles=m.get("decode_cycles_estimate"), latency_us=m.get("latency_us")))
                    if code == "da2_1152_r12":
                        break
                if code == "da2_1152_r12":
                    break
        (out / "sweep.json").parent.mkdir(parents=True, exist_ok=True)
        (out / "sweep.json").write_text(json.dumps(rows, indent=2) + "\n", encoding="utf-8")
        for r in rows:
            print(f"{r['code']:15} P={r['p_act']:2} C={r['c_act']:2} ok={r['ok']!s:5} cycles={r['cycles']} "
                  f"latency_us={r['latency_us']} {'; '.join(r['issues'])}")
        return 0
    res = select(t, a.code, a.max_latency_us, a.min_info_mbps)
    print(json.dumps(res, indent=2) if res else "NO_CONFIGURATION_MEETS_REQUIREMENT")
    return 0 if res else 1


if __name__ == "__main__":
    raise SystemExit(main())
