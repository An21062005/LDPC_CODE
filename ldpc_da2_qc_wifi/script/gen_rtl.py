"""Generate the H-dependent RTL tables for the three cores (802.11n code).

Outputs (code/rtl/generated/):
  ldpc_code_pkg.sv      package: LDPC_N/M/E/DVMAX/DCMAX, VN_PTR, CN_PTR, CN_EDGE
  serial_rom.v          order ROM: {edge address, slot, last} for both phases
                        (+ base-matrix block tables for the QC core)

Edges are numbered in VN-major order (column n, increasing row), matching
script/ldpc_common.py. `python script/gen_rtl.py --check` verifies that the
committed files equal what H produces.
"""
import argparse
from pathlib import Path
import sys

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from ldpc_common import CODES, DEFAULT_CODE, ROOT, base_matrix, edges, load_h  # noqa: E402

OUT = ROOT / "code/rtl/generated"
HEADER = (f"// GENERATED by script/gen_rtl.py from code/data/base_matrices/{CODES[DEFAULT_CODE]['file']}"
          f" (Z={CODES[DEFAULT_CODE]['z']}) - do not edit.\n")


def clog2(x):
    return int(x - 1).bit_length()


def tables(h):
    cn, vn = edges(h)
    m, n = h.shape
    e = len(vn)
    vn_ptr = np.searchsorted(vn, np.arange(n + 1))
    order = np.lexsort((vn, cn))                 # CN-major, then increasing VN
    cn_sorted = cn[order]
    cn_ptr = np.searchsorted(cn_sorted, np.arange(m + 1))
    return dict(n=n, m=m, e=e, vn=vn, cn=cn, vn_ptr=vn_ptr, cn_ptr=cn_ptr, cn_edge=order,
                dvmax=int(np.diff(vn_ptr).max()), dcmax=int(np.diff(cn_ptr).max()))


def packed(name, values, width):
    items = ", ".join(f"{width}'d{int(v)}" for v in reversed(list(values)))
    return f"localparam [{len(values)}*EW_T-1:0] {name} = {{{items}}};\n"


def render(t):
    ew_t = clog2(t["e"] + 1)
    # One package holds the code constants and the H tables. Synthesisable RTL
    # imports it instead of `include: the Vivado block-design module reference
    # parser does not resolve include directories reliably.
    pkg = HEADER + "package ldpc_code_pkg;\n"
    pkg += "".join(f"  localparam integer LDPC_{k.upper()} = {t[k]};\n" for k in ("n", "m", "e", "dvmax", "dcmax"))
    pkg += f"  localparam integer EW_T = {ew_t};\n"
    pkg += "  " + packed("VN_PTR", t["vn_ptr"], ew_t) + "  " + packed("CN_PTR", t["cn_ptr"], ew_t)
    pkg += "  " + packed("CN_EDGE", t["cn_edge"], ew_t)

    ew = clog2(t["e"])
    rows = []
    for i in range(t["e"]):                      # VN phase: order index = edge address
        node = t["vn"][i]
        slot = i - t["vn_ptr"][node]
        rows.append((i, i, slot, int(i == t["vn_ptr"][node + 1] - 1)))
    cn_sorted = t["cn"][t["cn_edge"]]
    for i in range(t["e"]):                      # CN phase: CN-major order
        node = cn_sorted[i]
        slot = i - t["cn_ptr"][node]
        rows.append(((1 << ew) + i, int(t["cn_edge"][i]), slot, int(i == t["cn_ptr"][node + 1] - 1)))
    dw = ew + 4 + 1
    cases = "".join(f"      {ew + 1}'d{a}: q <= {{{ew}'d{ed}, 4'd{s}, 1'b{l}}};\n" for a, ed, s, l in rows)
    port = f"""  always @(posedge clk) if (en) case (addr)
{cases}      default: q <= {dw}'d0;
    endcase
"""
    rom = HEADER + f"""// Order ROM: {{edge address, slot, last}}. Address = {{phase, order index}};
// phase 0 = VN order, 1 = CN order. Registered case ROM (UG901 style) so that
// synthesis maps it to block RAM; one instance per read port.
module serial_rom_port (
  input  wire          clk,
  input  wire          en,
  input  wire [{ew}:0]   addr,
  output wire [{ew - 1}:0] edge_o,
  output wire [3:0]    slot_o,
  output wire          last_o
);
  (* rom_style = "block" *) reg [{dw - 1}:0] q = {dw}'d0;
{port}  assign {{edge_o, slot_o, last_o}} = q;
endmodule

module serial_rom (
  input  wire          clk,
  input  wire          en_a,
  input  wire [{ew}:0]   addr_a,
  output wire [{ew - 1}:0] edge_a,
  output wire [3:0]    slot_a,
  output wire          last_a,
  input  wire          en_b,
  input  wire [{ew}:0]   addr_b,
  output wire [{ew - 1}:0] edge_b,
  output wire [3:0]    slot_b,
  output wire          last_b
);
  serial_rom_port pa (.clk(clk), .en(en_a), .addr(addr_a), .edge_o(edge_a), .slot_o(slot_a), .last_o(last_a));
  serial_rom_port pb (.clk(clk), .en(en_b), .addr(addr_b), .edge_o(edge_b), .slot_o(slot_b), .last_o(last_b));
endmodule
"""
    if t["dvmax"] > 15 or t["dcmax"] > 15:
        raise ValueError("slot field is 4 bits")
    pkg += qc_tables(t) + "endpackage\n"
    return {"ldpc_code_pkg.sv": pkg, "serial_rom.v": rom}


def qc_tables(t):
    """Per-block tables for ldpc_core_qc_pp.sv; blocks numbered row-major."""
    b = base_matrix(DEFAULT_CODE)
    z = CODES[DEFAULT_CODE]["z"]
    mb, nb = b.shape
    blocks = [(r, c) for r in range(mb) for c in range(nb) if b[r, c] >= 0]
    col_blk = [i for c in range(nb) for i, (_, cc) in enumerate(blocks) if cc == c]   # rows increasing
    row_blk = list(range(len(blocks)))                                                  # columns increasing
    col_ptr, row_ptr = [0], [0]
    for c in range(nb):
        col_ptr.append(col_ptr[-1] + sum(1 for _, cc in blocks if cc == c))
    for r in range(mb):
        row_ptr.append(row_ptr[-1] + sum(1 for rr, _ in blocks if rr == r))
    cslot = [col_blk.index(i) - col_ptr[blocks[i][1]] for i in range(len(blocks))]
    rslot = [i - row_ptr[blocks[i][0]] for i in range(len(blocks))]
    if max(max(col_ptr), max(row_ptr), z, len(blocks)) > 255:
        raise ValueError("8-bit table fields")

    def p8(name, vals):
        return f"localparam [{len(vals)}*8-1:0] {name} = {{" + ", ".join(f"8'd{v}" for v in reversed(vals)) + "};\n"
    text = (f"  localparam integer ZB = {z};\n  localparam integer MB = {mb};\n  localparam integer NB = {nb};\n"
            f"  localparam integer NBLK = {len(blocks)};\n  localparam integer DVMAX = {t['dvmax']};\n"
            f"  localparam integer DCMAX = {t['dcmax']};\n")
    for name, vals in (("BLK_SHIFT", [int(b[r, c]) for r, c in blocks]), ("BLK_ROW", [r for r, _ in blocks]),
                       ("BLK_COL", [c for _, c in blocks]), ("BLK_RSLOT", rslot), ("BLK_CSLOT", cslot),
                       ("COL_PTR", col_ptr), ("COL_BLK", col_blk), ("ROW_PTR", row_ptr), ("ROW_BLK", row_blk)):
        text += "  " + p8(name, vals)
    return text


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true", help="compare instead of writing")
    a = p.parse_args(argv)
    t = tables(load_h())
    files = render(t)
    stale = [name for name, text in files.items()
             if not (OUT / name).is_file() or (OUT / name).read_text(encoding="ascii") != text]
    if a.check:
        print("GENERATED_RTL_" + ("STALE: " + ", ".join(stale) if stale else "UP_TO_DATE"))
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.vh"):                 # superseded by ldpc_code_pkg.sv
        old.unlink()
    for name, text in files.items():
        (OUT / name).write_text(text, encoding="ascii", newline="\n")
    print(f"N={t['n']} M={t['m']} E={t['e']} DVMAX={t['dvmax']} DCMAX={t['dcmax']} -> {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
